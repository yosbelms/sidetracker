#!/usr/bin/env python3
"""Generate immutable native DSP tables. Runtime/builds need no temp/ sources."""
from pathlib import Path
import math
import re

root = Path(__file__).resolve().parents[1]
fold = [float(v) for v in re.findall(r'[-+]?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?',
                                   (root / 'tools/reference_fold.txt').read_text())]
assert len(fold) == 4097
fold = fold[:4096]
quantize = lambda x: max(-32767, min(32767, round(x * 32767)))
tanh = [quantize(math.tanh(-8 + i/128)) for i in range(2049)]
fold = [quantize(x) for x in fold]
def integral(values):
    out = [0.0]
    for a, b in zip(values, values[1:]):
        out.append(out[-1] + (a+b)/(2*32767))
    center=out[len(out)//2]
    return [x-center for x in out]
def sweeten(x):
    mojo = abs(x)**.25
    return math.sin(x*mojo*math.pi/2)/mojo*.987654 if mojo else 0
sweet = [quantize(sweeten(-4 + i/256)) for i in range(2049)]
mu = [quantize(math.log1p(255*i/1024)/math.log(256)) for i in range(1025)]
arrays = [('int16_t','tanhCurve',tanh),('float','tanhIntegral',integral(tanh)),
          ('int16_t','foldCurve',fold),('float','foldIntegral',integral(fold)),
          ('int16_t','sweetenCurve',sweet),('int16_t','muLawCurve',mu)]
text = '// Generated by ../tools/generate_tables.py; do not edit.\n#include "Tables.h"\nnamespace samplefx { namespace palette {\n'
for typ, name, values in arrays:
    text += f'const {typ} {name}[{len(values)}] = {{\n'
    for i in range(0,len(values),8):
        def fmt(v):
            if typ != 'float': return str(v)
            s = format(v,'.9g')
            return s + ('f' if '.' in s or 'e' in s else '.0f')
        text += '    '+', '.join(map(fmt,values[i:i+8]))+',\n'
    text += '};\n'
text += '} }\n'
(root/'tables/Curves.cpp').write_text(text)
